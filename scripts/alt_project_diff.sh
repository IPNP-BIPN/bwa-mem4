#!/usr/bin/env bash
# `--alt-project` oracle diff: bwa-mem4 against fg-labs/bwa-mem3 0.18 (the fork, its binary) on the
# synthetic ALT fixtures of the fork's own regression tests (#775, #802). Every run must give the
# same SAM byte for byte, @PG lines excepted (they name each tool), and @HD, which the fork writes
# by default and bwa-mem2 (so bwa-mem4) does not; the fork's default HN:i and MQ:i tags are stripped for the
# same reason.
#
#   scripts/alt_project_diff.sh
#
# FORK      the fork's binary [reference/bwa-mem3-cpp/bwa-mem3.arm64]
# FORK_SRC  the fork's checkout, for its v0.18.0 test scripts [reference/bwa-mem3-cpp]
# OURS      our binary [target/release/bwa-mem4, built first]
#
# The fixtures are generated by the fork's Python, taken verbatim from
# test/regression/alt_project.sh and alt_project_primary.sh at v0.18.0: copy/paralog/ALT with a
# private SNP and a deletion (forward and FLAG-16 ALTs), an ALT-only clip, balanced and wide ALT
# indels, a read running off a divergent ALT, a lifted hit that clips 4 bases, a tandem repeat,
# symmetric ALT families, a BED that excludes one of two .alt lines for one ALT, a mixed
# excluded/retained pair of ALTs, and the primary-mode fixture (an ALT with a 600 bp ALT-only
# clip, reads only on it, a -H naming every contig). Each runs with projection off, keep-alt and
# primary, single-end and (where the fork pairs it) paired-end, with and without the BED.
set -euo pipefail
cd "$(dirname "$0")/.."

FORK="${FORK:-reference/bwa-mem3-cpp/bwa-mem3.arm64}"
FORK_SRC="${FORK_SRC:-reference/bwa-mem3-cpp}"
[ -x "$FORK" ] || { echo "no fork binary at $FORK (set FORK=)" >&2; exit 1; }
FORK="$(cd "$(dirname "$FORK")" && pwd)/$(basename "$FORK")"
if [ -z "${OURS:-}" ]; then
  cargo build --release --quiet
  OURS=target/release/bwa-mem4
fi
OURS="$(cd "$(dirname "$OURS")" && pwd)/$(basename "$OURS")"
W=work/alt_project
rm -rf "$W"
mkdir -p "$W/a" "$W/p"

# The body of the Python heredoc that opens at line $2 of the fork's v0.18.0 $1, checked to hold $3
# so a moved block fails loudly.
heredoc() {
  local body
  body=$(git -C "$FORK_SRC" show "v0.18.0:test/regression/$1" | awk -v s="$2" 'NR == s { p = 1; next } p && /^EOF$/ { exit } p')
  grep -qF "$3" <<<"$body" || { echo "fixture block at $1:$2 moved (no '$3')" >&2; exit 1; }
  printf '%s\n' "$body"
}
heredoc alt_project.sh 132 'random.seed(7)' > "$W/a/gen.py"
heredoc alt_project.sh 701 'Random(775119)' > "$W/a/gen_sym.py"
heredoc alt_project.sh 904 'Random(77501)' > "$W/a/gen_mix.py"
heredoc alt_project_primary.sh 90 'random.seed(23)' > "$W/p/gen.py"
(cd "$W/a" && python3 gen.py && python3 gen_sym.py && python3 gen_mix.py)
(cd "$W/p" && python3 gen.py)
# The #802 restriction fixture (alt_project.sh, built in shell there): fwd plus a later usable
# line for the same ALT, the first one excluded by the BED.
(cd "$W/a" && cp fwd.fa exclude.fa && cp fwd.fa.alt exclude.fa.alt &&
  printf 'chrA_alt1\t0\tchrA\t1\t60\t1500M3D497M\t*\t0\t0\t*\t*\n' >> exclude.fa.alt &&
  printf 'chrA\t3000\t3001\n' > exclude.bed && gzip -kn exclude.bed)

# Each tool indexes its own copy.
for d in a p; do
  for ref in "$W/$d"/*.fa; do
    for t in fork ours; do
      mkdir -p "$W/$d/$t"
      cp "$ref" "$W/$d/$t/"
      [ -f "$ref.alt" ] && cp "$ref.alt" "$W/$d/$t/"
    done
    b=$(basename "$ref")
    "$FORK" index "$W/$d/fork/$b" > /dev/null 2>&1
    "$OURS" index "$W/$d/ours/$b" > /dev/null 2>&1
  done
done

pass=0 fail=0
# run DIR REF NAME ARGS... -- READS...: the same mem command with both tools, SAM compared.
run() {
  local d=$1 ref=$2 name=$3
  shift 3
  local args=() reads=()
  while [ "$1" != -- ]; do args+=("$1"); shift; done
  shift
  for r in "$@"; do reads+=("$W/$d/$r"); done
  # bash 3.2 (macOS) calls an empty array unbound under `set -u`.
  args+=(-v 1)
  local o="$W/$d/out.$name"
  "$FORK" mem -t 2 "${args[@]}" "$W/$d/fork/$ref.fa" "${reads[@]}" 2> "$o.fork.log" | grep -v '^@PG\|^@HD' | sed -E 's/\t(HN|MQ):i:[0-9]+//g' > "$o.fork.sam" || true
  "$OURS" mem -t 2 "${args[@]}" "$W/$d/ours/$ref.fa" "${reads[@]}" 2> "$o.ours.log" | grep -v '^@PG\|^@HD' | sed -E 's/\t(HN|MQ):i:[0-9]+//g' > "$o.ours.sam" || true
  if [ ! -s "$o.fork.sam" ]; then
    echo "FAIL $name: the fork wrote nothing (see $o.fork.log)"; fail=$((fail + 1))
  elif cmp -s "$o.fork.sam" "$o.ours.sam"; then
    pass=$((pass + 1))
  else
    echo "FAIL $name: $(diff "$o.fork.sam" "$o.ours.sam" | grep -c '^[<>]') differing lines ($o.{fork,ours}.sam)"
    fail=$((fail + 1))
  fi
}
MODES=("off" "keep-alt" "primary")
mode_args() { [ "$1" = off ] && return; echo "--alt-project $1"; }

for m in "${MODES[@]}"; do
  # shellcheck disable=SC2046
  {
    for ref in fwd rev; do
      run a $ref "$ref.pe.$m" -I 400,10 $(mode_args $m) -- r1.fq r2.fq
      run a $ref "$ref.se.$m" $(mode_args $m) -- r1.fq
    done
    run a clip "clip.$m" $(mode_args $m) -- clip.fq
    for ref in bal1 bal2 bal5 bal35 bal40 wide end par tan; do
      run a $ref "$ref.$m" $(mode_args $m) -- $ref.fq
    done
    for ref in sym asym; do
      run a $ref "$ref.pe.$m" -I 575,175,1100,100 $(mode_args $m) -- sym.r1.fq sym.r2.fq
    done
    run a mix "mix.pe.$m" -I 400,10 $(mode_args $m) -- mix1.fq mix2.fq
    run a mix "mix.se.$m" $(mode_args $m) -- mixse.fq
    run p ref "p.pe.$m" $(mode_args $m) -- r1.fq r2.fq
    run p ref "p.se.$m" $(mode_args $m) -- se.fq
    run p ref "p.hdr.$m" -H "$W/p/allsq.hdr" $(mode_args $m) -- r1.fq r2.fq
    run p tan "p.tan.$m" $(mode_args $m) -- tan.fq
    run p bal40 "p.bal40.$m" $(mode_args $m) -- bal40.fq
  }
done
for m in keep-alt primary; do
  for bed in exclude.bed exclude.bed.gz; do
    run a exclude "exclude.pe.$m.$bed" -I 400,10 --alt-project $m --alt-project-exclude-bed "$W/a/$bed" -- r1.fq r2.fq
    run a exclude "exclude.se.$m.$bed" --alt-project $m --alt-project-exclude-bed "$W/a/$bed" -- r1.fq
  done
  run a mix "mix.pe.$m.bed" -I 400,10 --alt-project $m --alt-project-exclude-bed "$W/a/mix.bed" -- mix1.fq mix2.fq
  run a mix "mix.se.$m.bed" --alt-project $m --alt-project-exclude-bed "$W/a/mix.bed" -- mixse.fq
  run p ref "p.pe.$m.bed" --alt-project $m --alt-project-exclude-bed "$W/p/excl.bed" -- r1.fq r2.fq
  run p ref "p.se.$m.bed" --alt-project $m --alt-project-exclude-bed "$W/p/excl.bed" -- se.fq
done

echo "alt_project_diff: $pass identical, $fail differ"
[ "$fail" -eq 0 ]
